function esc(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

const path = 'app/(tabs)/cards.tsx';
let s = fs.readFileSync(path, 'utf8');

const sorted = [...pairs].sort((a, b) => b[0].length + b[1].length - (a[0].length + a[1].length));

for (const [es, en, key] of sorted) {
  const re = new RegExp(`tr\\(\\s*'${esc(es)}'\\s*,\\s*'${esc(en)}'\\s*\\)`, 'g');
  s = s.replace(re, `t('${key}')`);
}

fs.writeFileSync(path, s);
console.log('Migrated', pairs.length, 'pair patterns');
