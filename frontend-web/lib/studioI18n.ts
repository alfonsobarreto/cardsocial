const DICT: Record<StudioLocale, Record<string, string>> = {
  en: EN,
  es: ES,
  it: IT,
  fr: FR,
  pt: PT,
  de: DE,
};

function bucketForLocale(l: StudioLocale): StudioLocale {
  if (l === 'es' || l === 'en' || l === 'it' || l === 'fr' || l === 'pt' || l === 'de') return l;
  return 'en';
}

export function studioT(locale: StudioLocale, key: string, vars?: Record<string, string | number>): string {
  const b = bucketForLocale(locale);
  let s = DICT[b][key] ?? EN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

const LOCALE_KEY = 'card-social-studio-locale';

/** Ordem: idiomas del `navigator` → primer locale soportado; si ninguno, `en`. */
export function readBrowserLocale(): StudioLocale {
  if (typeof window === 'undefined' || !navigator) return 'en';
  const list =
    typeof navigator.languages === 'object' && navigator.languages && navigator.languages.length > 0
      ? Array.from(navigator.languages)
      : [navigator.language || 'en'];
  for (const raw of list) {
    const c = String(raw).toLowerCase().split('-')[0] ?? 'en';
    if (c === 'es' || c === 'en' || c === 'it' || c === 'fr' || c === 'pt' || c === 'de') {
      return c;
    }
  }
  return 'en';
}

export function readStoredLocale(): StudioLocale | null {
  if (typeof window === 'undefined') return null;
  try {
    const raw = window.localStorage.getItem(LOCALE_KEY);
    if (raw === 'es' || raw === 'en' || raw === 'it' || raw === 'fr' || raw === 'pt' || raw === 'de') return raw;
  } catch {
    /* ignore */
  }
  return null;
}

export function writeStoredLocale(locale: StudioLocale): void {
  if (typeof window === 'undefined') return;
  try {
    window.localStorage.setItem(LOCALE_KEY, locale);
  } catch {
    /* ignore */
  }
}

export function studioLocaleFromQuery(q: string | null | undefined): StudioLocale | null {
  const v = String(q || '')
    .trim()
    .toLowerCase();
  if (v === 'es' || v === 'en' || v === 'it' || v === 'fr' || v === 'pt' || v === 'de') return v;
  return null;
}
